from google.colab import auth
auth.authenticate_user()

import gspread
from google.auth import default

credentials, project = default()
gc = gspread.authorize(credentials)

"""# Membaca Google Spreadsheet"""

# URL Google Spreadsheet
spreadsheet_url = "https://docs.google.com/spreadsheets/d/1Uzyp9Mj7oAm7xBe8KKsG32x0Vd-wL0c9evsOme2nQfQ/edit?gid=1629255624#gid=1629255624"

# Membuka file spreadsheet
spreadsheet = gc.open_by_url(spreadsheet_url)

# Membaca sheet Raw_Data
worksheet = spreadsheet.worksheet("kanpres_gwt_table")

# Mengambil data
data = worksheet.get_all_records()

# Mengubah menjadi DataFrame Pandas
import pandas as pd

df = pd.DataFrame(data)

# Menampilkan data
df.head()

"""# Pengelolaan Data"""

#Mengubah struktur data wide menjadi long
data_long = pd.wide_to_long(
    df,
    stubnames=['persentase_gwt', 'volume_gwt'],
    i='Tanggal',
    j='Tangki',
    sep="_",
    suffix='.+'
).reset_index()

#mengatur format tanggal
data_long['Tanggal'] = pd.to_datetime(
    data_long['Tanggal'],
    dayfirst=True
).dt.strftime('%m/%d/%Y')

# Mengganti nama kolom
data_long = data_long.rename(columns={
    'persentase_gwt': 'persentase',
    'volume_gwt': 'volume'
})

data_long.head()

#Mengubah nilai persentase menjadi numerik
data_long['persentase'] = (
    data_long['persentase']
    .astype(str)
    .str.replace('%', '', regex=False)
    .str.replace(',', '.', regex=False)
    .astype(float)
);

data_long.head()

# Mengubah nilai volume menjadi numerik
data_long['volume'] = (
    data_long['volume']
    .astype(str)
    .str.replace(' m³', '', regex=False)
    .str.replace(',', '.', regex=False)
    .astype(float)
)

#mengurutkan data
data_long = data_long.sort_values(
    ['Tanggal', 'Tangki']
).reset_index(drop=True)

data_long = data_long[['Tanggal', 'Tangki', 'persentase', 'volume', 'Latest Record']]
data_long.head()

"""# Menyimpan hasil pengelolaan ke sheet baru"""

# cek apakah sheet sudah tersedia
try:
  result_sheet = spreadsheet.worksheet('result_gwt_data')

except gspread.WorksheetNotFound:
  result_sheet = spreadsheet.add_worksheet(
      title='result_gwt_data',
      rows=1000,
      cols=4
  )

# Mengubah dataframe menjadi data yang bisa disimpan
output = [data_long.columns.tolist()] + (
    data_long.fillna("").values.tolist()
)

output

# menulis hasil ke google spreadsheet
result_sheet.clear()
result_sheet.update(
    values=output,
    range_name='A1'
)

print('data berhasil disimpan')

